-- Read/unread для знахідок (запит Миколи 2026-08-11: «бачити нові і
-- прочитані, як у месенджерах» — щоб у дашборді було видно, ЩО нового
-- з'явиться в ранковому звіті, ще до самого звіту).
--
-- viewed_at NULL = непрочитана. Ставиться кнопкою «Mark all as read» на
-- Findings (admin) — автоматичного «прочитано при відкритті сторінки»
-- свідомо нема: людина хоче САМА вирішувати, що вже переглянула.
--
-- Backfill: усе, старше доби на момент міграції, одразу «прочитане» —
-- інакше лічильник стартував би з сотень історичних рядків і втратив сенс
-- як сигнал «є нове».

ALTER TABLE seen_items
    ADD COLUMN IF NOT EXISTS viewed_at timestamptz;

UPDATE seen_items
   SET viewed_at = now()
 WHERE viewed_at IS NULL
   AND first_seen < now() - interval '1 day';
