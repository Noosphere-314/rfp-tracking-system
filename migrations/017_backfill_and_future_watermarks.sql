-- 017: одноразовий добір історії для джерел, які не дали жодного айтема,
-- + прибирання водяних знаків із МАЙБУТНЬОГО (розбір алертів 31.08.2026).
--
-- Привід — алерт «8 source(s) have produced nothing for 14+ days». Перевірка
-- наживо з прод-сервера показала, що жодне з восьми джерел не зламане: усі
-- ендпойнти віддають 200 і реальний контент. У п'яти (dYdX id 6, Polygon,
-- Safe, Karma GAP, Filecoin) причина інша й системна.
--
-- Ці рядки засіяні з enabled = false («Stage 3 — вмикаються з адмінки»), тож
-- у первинному засіві вони не брали участі. А _watermark() при порожньому
-- last_item_at падає на last_success_at, який оновлюється щопрогону НАВІТЬ
-- коли знайдено нуль айтемів. Вікно назавжди лишається ~72 години, і джерело
-- ловить лише теми, створені за останні дві доби. У тихій grants-категорії,
-- де найновіша тема від 2026-03-19, це нуль назавжди — разом із вічним
-- алертом і повністю невидимою історією.
--
-- backfilled_at робить «рівно один раз» явним станом рядка, а не збігом
-- порожніх полів: last_success_at у цих джерел давно не порожній.

ALTER TABLE sources ADD COLUMN backfilled_at timestamptz;

-- Водяний знак із МАЙБУТНЬОГО замикає джерело назавжди й НЕ ловиться
-- перевіркою темних джерел (вона шукає last_item_at < now() - 14d).
-- DAOstar мапить ts на closeDate — це дедлайн пулу, тобто дата попереду.
-- Один пул із 2028-09-30 підняв last_item_at у 2028 рік, після чого кожен
-- реальний пул відсікався як «застарий». Джерело мовчало місяцями, і бот
-- мовчав про нього. NULL повертає його в добір нижче.
UPDATE sources SET last_item_at = NULL WHERE last_item_at > now();

-- Хто вже колись щось приносив — добору не потребує: його історію засів
-- або звичайні прогони вже забрали.
UPDATE sources SET backfilled_at = now() WHERE last_item_at IS NOT NULL;
